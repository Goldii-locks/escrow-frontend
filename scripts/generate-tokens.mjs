#!/usr/bin/env node
/**
 * scripts/generate-tokens.mjs
 *
 * Reads the `@theme` blocks in `app/globals.css` and writes a typed
 * TypeScript module (`app/lib/generated_tokens.ts`) with every
 * `--color-*` custom property as a named export.
 *
 * Why:
 *   Previously each component kept its own hex table (a copy of the CSS
 *   tokens), meaning a design change required editing several files and
 *   keeping tests in sync (issue #680). This script makes `globals.css`
 *   the single source of truth: the TypeScript tokens are derived, not
 *   maintained by hand.
 *
 * Usage:
 *   node scripts/generate-tokens.mjs
 *   # or via npm:
 *   npm run generate-tokens
 *
 * Output:
 *   app/lib/generated_tokens.ts  — auto-generated, do NOT edit by hand.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = dirname(fileURLToPath(new URL(".", import.meta.url)));
const CSS_PATH = resolve(ROOT, "app/globals.css");
const OUT_PATH = resolve(ROOT, "app/lib/generated_tokens.ts");

const css = readFileSync(CSS_PATH, "utf8");

/** Parse every `--color-<name>: <hex>` declaration inside `@theme { … }`. */
function parseThemeColours(css) {
  const tokens = new Map();
  const themeBlock = /@theme[^{]*\{([^}]*)\}/g;
  let block;
  while ((block = themeBlock.exec(css)) !== null) {
    const decl = /--color-([a-z0-9-]+)\s*:\s*([^;]+);/g;
    let match;
    while ((match = decl.exec(block[1])) !== null) {
      tokens.set(match[1], match[2].trim().toLowerCase());
    }
  }
  return tokens;
}

const tokens = parseThemeColours(css);

if (tokens.size === 0) {
  console.error("No --color-* tokens found in", CSS_PATH);
  process.exit(1);
}

// Build an identifier from a token name: "surface-card" → "surfaceCard"
function toCamel(name) {
  return name.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
}

const lines = [
  "/**",
  " * generated_tokens.ts — AUTO-GENERATED by scripts/generate-tokens.mjs",
  " *",
  " * DO NOT EDIT BY HAND. Run `npm run generate-tokens` to regenerate.",
  " *",
  " * Source of truth: app/globals.css `@theme` block.",
  " * Every `--color-<name>` CSS custom property becomes a typed constant here.",
  " * Components that previously kept their own hex tables should import from",
  " * this module instead (issue #680).",
  " */",
  "",
  "// ---------------------------------------------------------------------------",
  "// Typed map — all colour tokens keyed by their CSS-variable suffix",
  "// ---------------------------------------------------------------------------",
  "",
  "export const THEME_TOKENS = {",
];

for (const [name, value] of tokens) {
  lines.push(`  "${name}": "${value}",`);
}

lines.push("} as const;");
lines.push("");
lines.push("export type ThemeToken = keyof typeof THEME_TOKENS;");
lines.push("export type ThemeTokenValue = (typeof THEME_TOKENS)[ThemeToken];");
lines.push("");
lines.push("// ---------------------------------------------------------------------------");
lines.push("// Convenience named exports (camelCase)");
lines.push("// ---------------------------------------------------------------------------");
lines.push("");

for (const [name, value] of tokens) {
  const camel = toCamel(name);
  lines.push(`/** CSS: --color-${name}: ${value} */`);
  lines.push(
    `export const color${camel.charAt(0).toUpperCase() + camel.slice(1)} = "${value}" as const;`
  );
  lines.push("");
}

const output = lines.join("\n");
writeFileSync(OUT_PATH, output, "utf8");
console.log(`✓ Generated ${tokens.size} colour tokens → ${OUT_PATH}`);
